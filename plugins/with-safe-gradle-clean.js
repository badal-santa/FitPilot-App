// Makes `./gradlew clean` work on this React Native project.
//
// `clean` first cleans every library, deleting their generated codegen JNI
// dirs (node_modules/*/android/build/generated/source/codegen/jni). Then the
// app's `externalNativeBuildClean*` task re-runs CMake, whose autolinking
// config still add_subdirectory()s those now-missing dirs, and the build fails
// with "add_subdirectory given source ... which is not an existing directory".
//
// That task only removes the app's intermediate C++ output (android/app/.cxx),
// so skip it and delete .cxx as part of `clean` instead — same end result.
// A config plugin (not a hand edit) because android/ is regenerated by prebuild.
const { withAppBuildGradle } = require("expo/config-plugins");

const MARKER = "// @generated with-safe-gradle-clean";

const SNIPPET = `
${MARKER}
tasks.configureEach { task ->
    if (task.name.startsWith("externalNativeBuildClean")) {
        task.enabled = false
    }
}
tasks.named("clean") {
    delete file(".cxx")
}
`;

module.exports = function withSafeGradleClean(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (!cfg.modResults.contents.includes(MARKER)) {
      cfg.modResults.contents += SNIPPET;
    }
    return cfg;
  });
};
